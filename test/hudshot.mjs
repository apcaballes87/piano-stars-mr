import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.grantPermissions(['microphone']);
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('http://localhost:8765/index.html');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('ps.view', '"screen"'); localStorage.setItem('ps.input', '"mic"'); });
await page.reload(); await page.waitForTimeout(500);
await page.click('#micBtn'); await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/menu-mictest.png' });
const rows = await page.$$('.song'); await (await rows[0].$('.play')).click();
await page.waitForFunction(() => window.__ps.app.game && window.__ps.app.game.waiting, null, { timeout: 20000 });
await page.evaluate(() => { const g = window.__ps.app.game; window.__ps.app.input(g.notes[g.nextIdx].midi, 0, 'finger'); window.__ps.app.input(g.notes[g.nextIdx].midi, 0, 'mic'); });
await page.waitForTimeout(300);
console.log('after dual input (dedupe):', await page.evaluate(() => { const g = window.__ps.app.game; return JSON.stringify({ next: g.nextIdx, perfect: g.perfect }); }));
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/hud-status.png' });
console.log('errors', errs);
await browser.close();
